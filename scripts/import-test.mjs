import { chromium } from 'playwright-core'
const [file, OUT] = process.argv.slice(2)
const b = await chromium.launch({ channel: 'msedge', headless: true })
const p = await (await b.newContext({ viewport: { width: 1400, height: 950 } })).newPage()
const errs = []; p.on('pageerror', (e) => errs.push(String(e)))
await p.goto('http://127.0.0.1:4174/')
await p.waitForSelector('.home')
await p.setInputFiles('input[type=file]', file)
await p.waitForSelector('.trip-card-name')
await p.screenshot({ path: `${OUT}/sa-home.png` })
await p.locator('.trip-card').first().click()
await p.waitForSelector('.day')
await p.locator('#day-7').scrollIntoViewIfNeeded()
await p.locator('#day-7 .day-plan-bar input[type=time]').fill('09:00')
await p.waitForTimeout(800)
await p.screenshot({ path: `${OUT}/sa-plan.png` })
console.log('days', await p.locator('.day').count(), 'stops on plan', await p.locator('.timeline .stop').count())
await p.getByRole('button', { name: /Saved/ }).click()
await p.waitForTimeout(800)
console.log('saved', await p.locator('.stop-list .stop').count())
await p.screenshot({ path: `${OUT}/sa-saved.png` })
console.log('errs', errs); await b.close()
