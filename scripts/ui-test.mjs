import { chromium } from 'playwright-core'
const OUT = process.argv[2]
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const ctx = await browser.newContext({ viewport: { width: 1400, height: 950 }, deviceScaleFactor: 1 })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
page.on('console', (m) => m.type() === 'error' && !m.text().includes('ERR_') && errors.push(m.text()))
await page.goto('http://127.0.0.1:4174/')
await page.waitForTimeout(600)
await page.screenshot({ path: `${OUT}/u1-empty.png` })
await page.getByRole('button', { name: /Plan my first trip/ }).click()
await page.getByPlaceholder('e.g. Lisbon, Portugal').fill('Lisbon, Portugal')
await page.screenshot({ path: `${OUT}/u2-form.png` })
await page.getByRole('button', { name: 'Create trip' }).click()
const day1 = page.locator('#day-0')
for (const q of ['Tower of Belem', 'Jeronimos Monastery', 'Time Out Market Lisboa', 'Praca do Comercio']) {
  await day1.locator('.add-row input').fill(q)
  await day1.getByRole('button', { name: 'Search' }).click()
  await day1.locator('.results li button').first().waitFor({ timeout: 15000 })
  await day1.locator('.results li button').first().click()
  await page.waitForTimeout(1100)
}
await day1.locator('.day-plan-bar input[type=time]').fill('09:00')
await day1.locator('.day-title-input').fill('Belém & the riverfront')
await day1.locator('.day-title-input').blur()
await page.locator('.stop-badge').first().click()
await page.waitForTimeout(500)
await page.screenshot({ path: `${OUT}/u3-plan.png` })
for (const b of await day1.locator('button.stop-badge').all()) { if (!(await b.textContent()).includes('✓')) await b.click() ; await page.waitForTimeout(150) }
await page.waitForTimeout(700)
await page.screenshot({ path: `${OUT}/u4-confetti.png` })
await page.waitForTimeout(2500)
await page.locator('.stop .more').first().click()
await page.screenshot({ path: `${OUT}/u5-menu.png` })
await page.keyboard.press('Escape'); await page.mouse.click(5, 300)
await page.setViewportSize({ width: 390, height: 844 })
await page.waitForTimeout(500)
await page.screenshot({ path: `${OUT}/u6-phone-plan.png` })
await page.locator('.back').click()
await page.waitForTimeout(500)
await page.screenshot({ path: `${OUT}/u7-phone-home.png` })
await page.setViewportSize({ width: 1400, height: 950 })
await page.waitForTimeout(300)
await page.screenshot({ path: `${OUT}/u8-home.png` })
console.log('errors', errors)
await browser.close()
