import { chromium } from 'playwright-core'
const [file, OUT] = process.argv.slice(2)
const b = await chromium.launch({ channel: 'msedge', headless: true })
const p = await (await b.newContext({ viewport: { width: 1400, height: 950 } })).newPage()
const errs = []; p.on('pageerror', (e) => errs.push(String(e)))
await p.goto('http://127.0.0.1:4176/')
await p.setInputFiles('input[type=file]', file)
await p.locator('.trip-card').first().click()
await p.waitForSelector('#day-7')
await p.locator('#day-7 .day-plan-bar input[type=time]').fill('09:00')
await p.waitForTimeout(9000)
console.log((await p.locator('#day-7 .leg, #day-7 .stop-clock').allTextContents()).join('\n'))
await p.screenshot({ path: `${OUT}/road-desktop.png` })
await p.context().setOffline(true)
await p.reload(); await p.waitForSelector('#day-7'); await p.waitForTimeout(1500)
console.log('offline legs:', (await p.locator('#day-7 .leg').allTextContents()).join(' / '))
console.log('errs', errs); await b.close()
